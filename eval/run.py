"""Baseline-first offline evaluation. Input: independently labelled synthetic JSONL.
Run: python -m eval.run baseline answers.jsonl results/baseline.jsonl
Then: python -m eval.run hmh answers.jsonl results/hmh.jsonl --baseline results/baseline.jsonl
No labels are generated by this script. HMH makes one billable scorer request per answer.
"""
import argparse
import hashlib
import json
from pathlib import Path
from engine.core import load_pack, pack_hash, utc_now, decide
from engine.scorer import score


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=["baseline", "hmh"])
    parser.add_argument("answers", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--baseline", type=Path)
    args = parser.parse_args()
    pack = load_pack(Path(__file__).resolve().parents[1] / "packs/fictional_savings_v1.json")
    clauses = {c["id"]: c for c in pack["clauses"]}
    raw = args.answers.read_bytes()
    dataset_hash = hashlib.sha256(raw).hexdigest()
    rows = [json.loads(line) for line in raw.decode().splitlines() if line.strip()]
    ids = set()
    for r in rows:
        if r["id"] in ids or r["clause_id"] not in clauses or r["human_verdict"] not in {"understood", "partial", "misunderstood", "no_evidence"}:
            raise ValueError("Invalid/duplicate labelled row")
        if r.get("label_status") != "reconciled" or len(set(r.get("reviewers", []))) < 2:
            raise ValueError("Two independent reviewers and reconciled labels required")
        ids.add(r["id"])
    if args.mode == "hmh":
        if not args.baseline:
            parser.error("Run baseline first and provide --baseline")
        baseline = [json.loads(line) for line in args.baseline.read_text().splitlines()]
        if {r["id"] for r in baseline} != ids or any(r["mode"] != "baseline" or r["dataset_hash"] != dataset_hash or r["pack_hash"] != pack_hash(pack) for r in baseline):
            raise ValueError("Baseline must cover the exact same labelled dataset and rubric")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("x") as out:
        for r in rows:
            record = dict(r, mode=args.mode, timestamp=utc_now(), dataset_hash=dataset_hash, pack_hash=pack_hash(pack))
            if args.mode == "baseline":
                # Intentionally weak affirmative-only comparator, not an understanding model.
                normal = r["answer"].casefold().strip(" .!?।")
                record["accepted"] = normal in {"yes", "yes yes", "haan", "haan haan", "हाँ", "हां", "जी हाँ", "theek hai", "ठीक है"}
            else:
                try:
                    from dataclasses import asdict
                    e = score(r["answer"], clauses[r["clause_id"]])
                    record["evidence"] = asdict(e)
                    record["accepted"] = decide(e, clauses[r["clause_id"]]["critical"], 1) == "pass"
                except Exception as exc:
                    record.update(accepted=False, error_type=type(exc).__name__)
            out.write(json.dumps(record, ensure_ascii=False) + "\n")
            out.flush()
    print(f"Saved {len(rows)} predictions; this is answer-level evaluation, not session recovery.")

if __name__ == "__main__":
    main()
